from __future__ import annotations

from contextlib import contextmanager
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
from typing import Any
import uuid


def ensure_new(*paths) -> None:
    """Fail before expensive work, including abandoned pending destinations."""
    for value in paths:
        path = Path(value)
        if path.exists() or path.is_symlink():
            raise FileExistsError(f"Refusing to overwrite existing output: {path}")
        for parent in path.parents:
            if parent.exists() and not parent.is_dir():
                raise NotADirectoryError(f"Output parent is not a directory: {parent}")



def ensure_outputs_new(*paths):
    for value in paths:
        path = Path(value)
        ensure_new(path, path.with_name(path.name + ".pending"),
                   path.with_name(path.name + ".publishing"))


def ensure_separate_artifacts(output, *artifacts):
    destination = Path(output).expanduser().resolve()
    for value in artifacts:
        if value is not None:
            artifact = Path(value).expanduser().resolve()
            if destination.is_relative_to(artifact) or artifact.is_relative_to(destination):
                raise ValueError(f"Output and artifact paths overlap: {destination}, {artifact}")


def write_csv(table, path, **kwargs):
    path = Path(path)
    pending = path.with_name(path.name + ".pending")
    ensure_outputs_new(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with pending.open("x", encoding="utf-8", newline="") as stream:
        table.to_csv(stream, **kwargs)
        stream.flush()
        __import__("os").fsync(stream.fileno())
    ensure_new(path)
    pending.rename(path)
    return path


def require_inputs(*paths) -> None:
    for value in paths:
        path = Path(value)
        if not path.is_file():
            raise FileNotFoundError(f"Required input is missing: {path}")
        with path.open("rb") as stream:
            stream.read(1)


def _publish_text(path, text, *, pending_suffix=".pending"):
    path = Path(path)
    pending = path.with_name(path.name + pending_suffix)
    ensure_new(path, pending)
    path.parent.mkdir(parents=True, exist_ok=True)
    with pending.open("x", encoding="utf-8") as stream:
        stream.write(text)
        stream.flush()
        __import__("os").fsync(stream.fileno())
    # Reuse the artifact publication convention: complete name appears last.
    ensure_new(path)
    pending.rename(path)
    return path


def _fmt(value: Any) -> str:
    return f"{value:.6f}" if isinstance(value, float) else str(value)


def write_stage_report(output_dir, title, sections, filename="v2_stage_report.md"):
    lines = [f"# {title}", "", "Generated by the Venus / Magellan V2 pipeline.", ""]
    for heading, payload in sections:
        lines.extend([f"## {heading}", ""])
        for key, value in payload.items():
            lines.append(f"- **{key}**: {_fmt(value)}")
        lines.append("")
    return _publish_text(Path(output_dir) / filename, "\n".join(lines))


def write_json(path, payload):
    return _publish_text(path, json.dumps(payload, indent=2, default=str, allow_nan=False) + "\n")


@contextmanager
def stage_run(output_dir, stage, configuration, inputs, outputs):
    """Record configuration now; publish completion only after stage success."""
    directory = Path(output_dir)
    complete = directory / f"{stage}_run.json"
    pending = directory / f"{stage}_run.json.pending"
    require_inputs(*inputs)
    ensure_new(complete, pending, complete.with_name(complete.name + ".publishing"),
               pending.with_name(pending.name + ".pending"))
    ensure_outputs_new(*outputs)
    def digest(path):
        h = hashlib.sha256()
        with Path(path).open("rb") as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b""):
                h.update(block)
        return h.hexdigest()
    run = {"run_id": uuid.uuid4().hex, "stage": stage, "status": "running",
           "created_utc": datetime.now(timezone.utc).isoformat(),
           "configuration": configuration.to_dict(),
           "inputs": [{"path": str(Path(p).resolve()), "sha256": digest(p)} for p in inputs],
           "outputs": [str(Path(p).resolve()) for p in outputs]}
    write_json(pending, run)
    yield run
    run["status"] = "complete"
    _publish_text(complete, json.dumps(run, indent=2, default=str, allow_nan=False) + "\n", pending_suffix=".publishing")
    # This is our own successfully completed run marker, never pre-existing data.
    pending.unlink()
